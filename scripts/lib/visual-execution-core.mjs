/** Distinct coarse colours: a basic-shape placeholder has very few. */
export function distinctColours(png, step = 7) {
  const seen = new Set(), ch = png.channels ?? 4, n = png.pixels.length / ch;
  for (let i = 0; i < n; i += step) { const o = i * ch; seen.add(((png.pixels[o] >> 4) << 8) | ((png.pixels[o + 1] >> 4) << 4) | (png.pixels[o + 2] >> 4)); if (seen.size > 64) break; }
  return seen.size;
}

/** A layer counts as generated by kind, by explicit provenance, or when its rights note says so (an image layer cannot launder AI output). */
export const isGeneratedLayer = (l) => l.kind === 'generated'
  || (l.kind === 'image' && (l.provenance?.origin === 'generated' || Boolean(l.generation) || /\b(ai[- ]generated|generated|midjourney|dall-?e|stable diffusion)\b|생성/i.test(l.rights_note ?? '')));
/**
 * Generation evidence is SELF_ATTESTED: provider/model/invocation_id are strings the caller typed. Only "the asset is
 * present in the final pixels" is machine-verified. A provider raw-response/metadata file (path + sha) is required;
 * without it the result is GENERATION_NOT_VERIFIED. Flat-colour art needs a recorded attestation (owner|agent + reason).
 */
function checkGeneration(l, file, png, baseDir) {
  const g = l.generation, reasons = [];
  let responseSha = null, attestation = null;
  if (!g || typeof g !== 'object') reasons.push('generation evidence missing (provider/model/invocation_id/mode/asset_sha256/response_ref)');
  else {
    keys(g, ['provider', 'model', 'invocation_id', 'mode', 'asset_sha256', 'response_ref', 'response_sha256', 'flat_art_attestation'], 'generation');
    if (object(g.flat_art_attestation)) keys(g.flat_art_attestation, ['by', 'reason', 'request_ref'], 'generation.flat_art_attestation');
    if (!ALL_MODES.includes(g.mode)) fail('GENERATION_MODE', `mode must be one of ${ALL_MODES.join(', ')}`);
    for (const k of ['provider', 'model', 'invocation_id']) if (typeof g[k] !== 'string' || !g[k].trim()) reasons.push(`generation.${k} missing`);
    if (g.asset_sha256 !== file.sha256) reasons.push('generation.asset_sha256 does not match the supplied asset bytes');
    if (!REAL_MODES.includes(g.mode)) reasons.push(`generation.mode "${g.mode}" is not a real generation`);
    if (typeof g.response_ref !== 'string' || !g.response_ref.trim() || typeof g.response_sha256 !== 'string') reasons.push('provider raw-response/metadata file (response_ref + response_sha256) missing');
    else {
      try { responseSha = localInput(g.response_ref, baseDir, g.response_sha256).sha256; }
      catch (e) { reasons.push(`provider response file not verifiable: ${e.message}`); }
    }
    attestation = g.flat_art_attestation ?? null;
  }
  const colours = distinctColours(png);
  // An agent attestation must name the request/brief it corresponds to (request_ref); an owner attestation need not.
  const attestOk = object(attestation) && ['owner', 'agent'].includes(attestation.by) && typeof attestation.reason === 'string' && attestation.reason.trim().length >= 8
    && (attestation.by === 'owner' || (typeof attestation.request_ref === 'string' && attestation.request_ref.trim().length >= 3));
  if (colours <= 2) reasons.push(`asset has only ${colours} distinct colour(s): a single-colour (near-flat/blank) asset is never a generated-image success, attested or not`);
  else if (colours <= 6 && !attestOk) reasons.push(`asset has only ${colours} distinct colours (<=6 threshold): near-flat art stays NOT_VERIFIED without flat_art_attestation {by: owner|agent, reason[, request_ref required for agent]}`);
  return { reasons, distinct_colours: colours, mode: g?.mode ?? null, evidence_level: 'SELF_ATTESTED', machine_verified: ['asset_in_final_png'], response_sha256: responseSha, flat_art_attestation: colours > 2 && colours <= 6 && attestOk ? { by: attestation.by, reason: attestation.reason } : null };
}


export const EXECUTION_VERSION = '1.0.0';
const object = (x) => x !== null && typeof x === 'object' && !Array.isArray(x);
const stable = (x) => Array.isArray(x) ? x.map(stable) : object(x) ? Object.fromEntries(Object.keys(x).sort().map((k) => [k, stable(x[k])])) : x;
export const digest = (x) => sha256(JSON.stringify(stable(x)));
export class ExecutionError extends Error {
  constructor(code, message) { super(message); this.name = 'ExecutionError'; this.code = code; }
}
const fail = (code, message) => { throw new ExecutionError(code, message); };
function keys(o, allowed, where) {
  if (!object(o)) fail('INVALID_INPUT', `${where} must be an object`);
  for (const k of Object.keys(o)) if (!allowed.includes(k)) fail('UNKNOWN_FIELD', `${where}.${k}`);
}
function str(s, where) { if (typeof s !== 'string' || !s.trim()) fail('INVALID_INPUT', `${where} is required`); }
function localInput(ref, baseDir, expected = null) {
  str(ref, 'local file ref');
  if (/^[a-z]+:\/\//i.test(ref)) fail('SOURCE_REQUIRED', 'materialize remote bytes with the existing authorized handoff first');
  const path = resolve(baseDir, ref);
  if (!existsSync(path)) fail('SOURCE_REQUIRED', `missing local bytes: ${ref}`);
  const bytes = readFileSync(path), hash = sha256(bytes);
  if (expected && hash !== expected) fail('SOURCE_CHANGED', `digest mismatch: ${ref}`);
  return { ref, path, bytes, sha256: hash };
}
function box(slot, canvas) {
  keys(slot, ['x', 'y', 'width', 'height'], 'slot');
  if (!['x', 'y', 'width', 'height'].every((k) => Number.isFinite(slot[k]) && slot[k] >= 0 && slot[k] <= 1) || slot.width <= 0 || slot.height <= 0 || slot.x + slot.width > 1.0000001 || slot.y + slot.height > 1.0000001) fail('INVALID_SLOT', 'slots use normalized 0–1 coordinates inside the canvas');
  return { x: Math.round(slot.x * canvas.width), y: Math.round(slot.y * canvas.height), width: Math.round(slot.width * canvas.width), height: Math.round(slot.height * canvas.height) };
}
function canvasOf(defaults, preset, task) {
  let width = 1080, height = 1080, ratio = null;
  for (const c of [defaults ?? {}, preset ?? {}, task ?? {}]) {
    keys(c, ['width', 'height', 'aspect_ratio'], 'canvas');
    if (c.width !== undefined) width = c.width;
    if (c.height !== undefined) height = c.height;
    if (c.aspect_ratio !== undefined) {
      if (!/^\d+:\d+$/.test(c.aspect_ratio)) fail('INVALID_GEOMETRY', 'aspect_ratio must be W:H');
      const [a, b] = c.aspect_ratio.split(':').map(Number);
      if (!a || !b) fail('INVALID_GEOMETRY', 'ratio terms must be positive');
      ratio = c.aspect_ratio;
      if (c.height !== undefined && c.width === undefined) width = Math.round(height * a / b);
      else {
        const resolvedHeight = Math.round(width * b / a);
        if (c.height !== undefined && Math.abs(c.height - resolvedHeight) > 1) fail('INVALID_GEOMETRY', 'explicit dimensions and ratio conflict');
        height = resolvedHeight;
      }
    } else if (c.width !== undefined || c.height !== undefined) ratio = null;
  }
  if (![width, height].every((n) => Number.isInteger(n) && n >= 64 && n <= 8192) || width * height > 25000000) fail('INVALID_GEOMETRY', 'canvas dimensions must be 64–8192px, at most 25MP');
  return { width, height, aspect_ratio: ratio ?? `${width}:${height}` };
}

function resolveProfiles(selection) {
  keys(selection, ['surface', 'artifact', 'brand'], 'profiles');
  const out = {};
  for (const axis of ['surface', 'artifact', 'brand']) {
    if (selection[axis] === undefined) { if (axis !== 'brand') fail('PROFILE_REQUIRED', axis); continue; }
    const p = loadAxisProfiles(axis)[selection[axis]];
    if (!p) fail('UNKNOWN_PROFILE', `${axis}: ${selection[axis]}`);
    if (axis === 'artifact' && p.modality !== 'visual') fail('PROFILE_MISMATCH', 'image execution requires a visual artifact');
    out[axis] = p;
  }
  if (!(out.surface.artifact_fit ?? []).includes(selection.artifact)) fail('PROFILE_MISMATCH', `${selection.artifact} is not declared for ${selection.surface}; select a suitable profile`);
  return out;
}

/** LLM-produced plan + request text -> reproducible, capability-aware packet. */
export async function compileExecution(plan, { baseDir = process.cwd(), preset = {} } = {}) {
  keys(plan, ['schema_version', 'request', 'source', 'profiles', 'task', 'layers', 'caption', 'job_ref'], 'plan');
  if (plan.schema_version !== EXECUTION_VERSION) fail('VERSION', 'unsupported execution plan version');
  str(plan.request, 'request');
  keys(plan.source, ['ref', 'sha256', 'scope'], 'source');
  if (!['source_bound', 'illustrative'].includes(plan.source.scope)) fail('SOURCE_SCOPE', 'declare source_bound or illustrative; this is not a verification verdict');
  const source = localInput(plan.source.ref, baseDir, plan.source.sha256);
  const profiles = resolveProfiles(plan.profiles);
  const task = plan.task ?? {};
  const taskKeys = ['canvas', 'theme', 'text_policy', 'density', 'watermark', 'watermark_layer'];
  keys(task, taskKeys, 'task'); keys(preset, taskKeys, 'preset');
  const defaults = profiles.surface.visual_defaults ?? {};
  const canvas = canvasOf(defaults.canvas, preset.canvas, task.canvas);
  const theme = { background: '#FFFFFF', foreground: '#222222', accent: '#536756', font_family: FONT_STACK,
    ...(profiles.brand?.execution_defaults?.theme ?? {}), ...(preset.theme ?? {}), ...(task.theme ?? {}) };
  keys(theme, ['background', 'foreground', 'accent', 'font_family'], 'theme');
  for (const k of ['background', 'foreground', 'accent']) if (!/^#[a-f0-9]{6}$/i.test(theme[k])) fail('INVALID_COLOR', `${k} must be #RRGGBB after token resolution`);
  str(theme.font_family, 'font_family');
  const policy = task.text_policy ?? preset.text_policy ?? profiles.artifact.text_policy?.profile ?? 'external_overlay';
  if (!['no_text', 'external_overlay', 'hybrid_template', 'integrated_generated_text'].includes(policy)) fail('TEXT_POLICY', policy);
  const density = { semantic: profiles.artifact.semantic_density?.level, visual: profiles.artifact.visual_density?.level, ...(preset.density ?? {}), ...(task.density ?? {}) };
  keys(density, ['semantic', 'visual'], 'density');
  for (const v of Object.values(density)) if (!['low', 'moderate', 'medium', 'high', 'medium-high'].includes(v)) fail('DENSITY', 'use an explicit supported density');
  const watermark = resolveWatermark(profiles.brand?.watermark_default, preset.watermark, task.watermark);
  const watermarkLayer = task.watermark_layer ?? preset.watermark_layer ?? 'overlay';
  if (!['overlay', 'background'].includes(watermarkLayer)) fail('WATERMARK_LAYER', 'use overlay or background; flattened images cannot accept a behind-plot edit');
  if (!Array.isArray(plan.layers) || !plan.layers.length || plan.layers.length > 32) fail('LAYERS', 'one to 32 layers required');
  const ids = new Set(), layers = [];
  for (const l of plan.layers) {
    keys(l, ['id', 'kind', 'slot', 'ref', 'sha256', 'mode', 'fit', 'rights_note', 'protect', 'focal_box', 'focal_min_area_ratio', 'focal_fallback', 'mockup_risk', 'text', 'source_ref', 'font_size', 'weight', 'align', 'max_lines', 'line_height', 'color', 'gradient', 'auto_scrim', 'letter_spacing', 'font_family', 'balance', 'emphasis', 'normalize', 'min_contrast', 'optical_margin', 'instruction', 'generation', 'provenance'], 'layer');
    if (!/^[a-z0-9][a-z0-9-]*$/.test(l.id ?? '') || ids.has(l.id)) fail('LAYER_ID', 'layer IDs must be unique lowercase slugs');
    ids.add(l.id);
    if (!['text', 'image', 'chart', 'generated', 'solid'].includes(l.kind)) fail('LAYER_KIND', String(l.kind));
    const permitted = {
      text: ['text', 'source_ref', 'font_size', 'weight', 'align', 'max_lines', 'line_height', 'color', 'letter_spacing', 'font_family', 'balance', 'emphasis', 'normalize', 'min_contrast', 'optical_margin'],
      chart: ['ref', 'sha256'],
      image: ['ref', 'sha256', 'mode', 'fit', 'rights_note', 'protect', 'focal_box', 'focal_min_area_ratio', 'focal_fallback', 'mockup_risk', 'provenance', 'generation'],
      generated: ['ref', 'sha256', 'mode', 'fit', 'rights_note', 'protect', 'focal_box', 'focal_min_area_ratio', 'focal_fallback', 'mockup_risk', 'instruction', 'generation'],
      solid: ['color', 'gradient', 'auto_scrim'],
    };
    keys(l, ['id', 'kind', 'slot', ...permitted[l.kind]], `layer ${l.id}`);
    let pixelSlot = box(l.slot, canvas);
    if (pixelSlot.width < 1 || pixelSlot.height < 1) fail('INVALID_SLOT', 'slot rounds to zero pixels');
    const next = { ...l, pixel_slot: pixelSlot };
    if (l.mockup_risk !== undefined && typeof l.mockup_risk !== 'boolean') fail('MOCKUP_RISK', `${l.id}: mockup_risk must be boolean`);
    if ((l.focal_min_area_ratio !== undefined || l.focal_fallback !== undefined) && l.focal_box === undefined) fail('FOCAL_CROP', `${l.id}: focal_min_area_ratio and focal_fallback require focal_box`);
    const overlapsNormalized = (a, b) => a.x < b.x + b.width && a.x + a.width > b.x && a.y < b.y + b.height && a.y + a.height > b.y;
    const coveredText = plan.layers.some((other) => other.kind === 'text' && overlapsNormalized(l.slot, other.slot));
    if (l.kind === 'text') {
      str(l.text, 'text'); str(l.source_ref, 'text source_ref');
      const knownRefs = new Set(['request', plan.source.ref, ...plan.layers.map((x) => x.ref).filter(Boolean)]);
      if (!knownRefs.has(l.source_ref.split('#')[0])) fail('TEXT_SOURCE', `unresolved source_ref: ${l.source_ref}`);
      if (policy === 'no_text') fail('TEXT_POLICY', 'no_text cannot contain text layers');
      next.font_size = l.font_size ?? Math.round(canvas.width * 0.05);
      next.weight = l.weight ?? 400; next.max_lines = l.max_lines ?? 3;
      next.align = l.align ?? 'start'; next.line_height = l.line_height ?? 1.25;
      if (!Number.isFinite(next.font_size) || next.font_size < 10 || next.font_size > 256 || !Number.isInteger(next.max_lines) || next.max_lines < 1 || next.max_lines > 30 || ![400, 500, 600, 700, 800, 900].includes(next.weight) || !['start', 'middle', 'end'].includes(next.align) || !(next.line_height >= 1.05 && next.line_height <= 2)) fail('TEXT_STYLE', l.id);
      if (l.color && !/^#[a-f0-9]{6}$/i.test(l.color)) fail('INVALID_COLOR', l.id);
      if (l.letter_spacing !== undefined && !(l.letter_spacing >= -0.1 && l.letter_spacing <= 0.3)) fail('TEXT_STYLE', `${l.id} letter_spacing must be -0.1..0.3 em`);
      if (l.font_family !== undefined) str(l.font_family, 'layer font_family');
      if (l.min_contrast !== undefined && !(l.min_contrast >= 1 && l.min_contrast <= 21)) fail('TEXT_STYLE', `${l.id} min_contrast must be 1..21`);
      for (const k of ['balance', 'normalize', 'optical_margin']) if (l[k] !== undefined && typeof l[k] !== 'boolean') fail('TEXT_STYLE', `${l.id} ${k} must be boolean`);
      if (l.emphasis !== undefined) {
        if (!Array.isArray(l.emphasis) || l.emphasis.length > 6 || !l.emphasis.every((e) => e && typeof e.match === 'string' && e.match && [400, 500, 600, 700, 800, 900].includes(e.weight ?? next.weight) && (e.color === undefined || /^#[a-f0-9]{6}$/i.test(e.color)))) fail('TEXT_STYLE', `${l.id} emphasis must be up to 6 {match, weight?, color?} spans`);
        for (const e of l.emphasis) if (!l.text.includes(e.match)) fail('EMPHASIS_NOT_FOUND', `${l.id}: "${e.match}" is not in the text`);
      }
    } else if (l.kind === 'solid') {
      if (!/^#[a-f0-9]{6}$/i.test(l.color ?? '')) fail('INVALID_COLOR', `${l.id} solid color must be #RRGGBB`);
      next.color = l.color;
      if (l.gradient !== undefined && !(Array.isArray(l.gradient) && l.gradient.length >= 2 && l.gradient.length <= 6 && l.gradient.every((st) => Array.isArray(st) && st.length === 2 && st.every((n) => Number.isFinite(n) && n >= 0 && n <= 1)))) fail('INVALID_GRADIENT', `${l.id} gradient must be 2-6 [offset, opacity] stops in 0..1 (top to bottom)`);
      if (l.auto_scrim !== undefined) {
        const a = l.auto_scrim;
        if (!a || typeof a !== 'object' || !Array.isArray(a.for) || !a.for.length || !a.for.every((x) => typeof x === 'string') || !(a.target_contrast >= 3 && a.target_contrast <= 21) || (a.max_opacity !== undefined && !(a.max_opacity > 0 && a.max_opacity <= 1)) || (a.feather !== undefined && !(a.feather >= 0 && a.feather < 1))) fail('INVALID_AUTO_SCRIM', `${l.id} auto_scrim needs {for:[text layer ids], target_contrast:3..21, max_opacity?}`);
      }
    } else if (l.kind === 'generated' && !l.ref) {
      str(l.instruction, 'generated layer instruction');
      next.status = 'RENDER_REQUIRED';
    } else {
      const file = localInput(l.ref, baseDir, l.sha256);
      next.sha256 = file.sha256;
      if (l.kind === 'chart') {
        // Chart values stay in their existing canonical spec, not in the prompt.
        const chart = JSON.parse(file.bytes);
        if (!['line', 'bar', 'flow'].includes(chart.type)) fail('CHART_BINDING', 'v1 binds line/bar/flow; use an existing rendered evidence image for another geometry');
      } else {
        next.mode = l.mode ?? 'exact_composite'; next.fit = l.fit ?? 'contain';
        if (!['exact_composite', 'cutout_composite'].includes(next.mode)) fail('EDIT_REQUIRED', 'supply the actual edited background/cutout; no inpainting is performed by this compositor');
        if (!['contain', 'cover'].includes(next.fit)) fail('IMAGE_FIT', 'contain or cover');
        if (l.kind === 'image' && next.fit === 'cover' && coveredText && l.focal_box === undefined) fail('FOCAL_CROP', `${l.id}: a cover-cropped photo beneath text requires focal_box and focal_fallback`);
        str(l.rights_note, 'rights_note');
        const png = decodePng(file.bytes);
        if (png.text[WATERMARK_CHUNK_KEY]) fail('INPUT_IS_DERIVATIVE', 'use the clean master; do not stack a previous watermark');
        if (next.mode === 'cutout_composite' && (png.channels !== 4 || !png.pixels.some((v, i) => i % 4 === 3 && v < 255))) fail('CUTOUT_REQUIRED', 'cutout mode requires a supplied PNG with actual alpha; no automatic background removal');
        next.native_geometry = { width: png.width, height: png.height };
        if (l.focal_box !== undefined) {
          if (next.fit !== 'cover') fail('FOCAL_CROP', `${l.id}: focal_box requires fit=cover`);
          const f = box(l.focal_box, png);
          if (f.width < 1 || f.height < 1) fail('FOCAL_CROP', `${l.id}: focal_box rounds to zero source pixels`);
          const ratio = l.focal_min_area_ratio ?? 1;
          if (!Number.isFinite(ratio) || ratio < 0.9 || ratio > 1) fail('FOCAL_CROP', `${l.id}: focal_min_area_ratio must be in [0.9,1]`);
          const evaluate = (slot) => {
            const scale = Math.max(slot.width / png.width, slot.height / png.height);
            const cropWidth = slot.width / scale, cropHeight = slot.height / scale;
            const crop = { x: (png.width - cropWidth) / 2, y: (png.height - cropHeight) / 2, width: cropWidth, height: cropHeight };
            const ix = Math.max(0, Math.min(f.x + f.width, crop.x + crop.width) - Math.max(f.x, crop.x));
            const iy = Math.max(0, Math.min(f.y + f.height, crop.y + crop.height) - Math.max(f.y, crop.y));
            const visibleRatio = ix * iy / (f.width * f.height);
            if (!Number.isFinite(crop.x) || !Number.isFinite(crop.y) || !Number.isFinite(crop.width) || !Number.isFinite(crop.height) || crop.width <= 0 || crop.height <= 0 || !Number.isFinite(visibleRatio)) fail('FOCAL_CROP', `${l.id}: focal visibility calculation is not finite`);
            return { crop, visibleRatio };
          };
          let evaluated = evaluate(pixelSlot), fallback = 'cover';
          if (evaluated.visibleRatio + 1e-9 < ratio) {
            if (l.focal_fallback !== undefined) {
              keys(l.focal_fallback, ['split_slot', 'r7_instruction'], `${l.id}.focal_fallback`);
              if (!l.focal_fallback.split_slot || typeof l.focal_fallback.r7_instruction !== 'string' || !l.focal_fallback.r7_instruction.trim()) fail('FOCAL_CROP', `${l.id}: fallback requires split_slot and r7_instruction`);
              const splitSlot = box(l.focal_fallback.split_slot, canvas);
              const splitEval = evaluate(splitSlot);
              const splitHasText = plan.layers.some((other) => other.kind === 'text');
              const splitOverlapsText = plan.layers.some((other) => other.kind === 'text' && overlapsNormalized(l.focal_fallback.split_slot, other.slot));
              if (splitEval.visibleRatio + 1e-9 >= ratio && splitHasText && !splitOverlapsText) {
                pixelSlot = splitSlot; next.slot = { ...l.focal_fallback.split_slot }; next.pixel_slot = splitSlot; evaluated = splitEval; fallback = 'split';
              } else {
                next.kind = 'generated'; next.ref = undefined; next.sha256 = undefined;
                next.instruction = l.focal_fallback.r7_instruction; next.status = 'RENDER_REQUIRED';
                fallback = 'r7-illustration';
              }
            } else fail('FOCAL_CROP', `${l.id}: visible focal area ${evaluated.visibleRatio.toFixed(4)} < ${ratio}; declare split_slot and r7_instruction fallback`);
          }
          next.focal_evidence = fallback === 'r7-illustration'
            ? { box: f, minimum_area_ratio: ratio, fallback, status: 'R7_RENDER_REQUIRED' }
            : { box: f, crop: evaluated.crop, visible_area_ratio: Number(evaluated.visibleRatio.toFixed(4)), minimum_area_ratio: ratio, fallback, status: 'PASS' };
        }
        if (isGeneratedLayer(l)) next.generation_check = checkGeneration(l, file, png, baseDir);
        for (const protectedBox of l.protect ?? []) {
          const p = box(protectedBox, { width: png.width, height: png.height });
          if (next.fit === 'cover') {
            const scale = Math.max(pixelSlot.width / png.width, pixelSlot.height / png.height);
            const ox = (pixelSlot.width - png.width * scale) / 2, oy = (pixelSlot.height - png.height * scale) / 2;
            if (ox + p.x * scale < -0.01 || oy + p.y * scale < -0.01 || ox + (p.x + p.width) * scale > pixelSlot.width + 0.01 || oy + (p.y + p.height) * scale > pixelSlot.height + 0.01) fail('PROTECTED_CROP', l.id);
          }
        }
      }
    }
    layers.push(next);
  }
  if (policy === 'no_text' && layers.some((l) => l.mockup_risk === true)) fail('TEXT_POLICY', 'mockup_risk requires a visible illustrative label; no_text conflicts');
  if (policy === 'no_text' && layers.some((l) => l.kind === 'chart')) fail('TEXT_POLICY', 'chart axes require text');
  if (policy === 'no_text' && watermark.enabled) fail('TEXT_POLICY', 'no_text and a text watermark conflict');
  const intersects = (a, b) => a.x < b.x + b.width && a.x + a.width > b.x && a.y < b.y + b.height && a.y + a.height > b.y;
  for (let i = 0; i < layers.length; i++) for (let j = 0; j < i; j++) {
    if (['text', 'chart'].includes(layers[j].kind) && intersects(layers[j].pixel_slot, layers[i].pixel_slot)) fail('LAYER_OVERLAP', `${layers[i].id} would obscure ${layers[j].id}; re-layout instead of overpainting text/evidence`);
  }
  const pending = layers.filter((l) => l.status === 'RENDER_REQUIRED');
  let legacy = null;
  if (plan.job_ref) {
    const f = localInput(plan.job_ref, baseDir); const job = JSON.parse(f.bytes);
    // Load the existing authority/lock/compiler only for jobs that actually use it.
    const core = await import('./visual-job-core.mjs');
    const errors = core.validateVisualJobFile(f.path);
    if (errors.length) fail('LEGACY_JOB_INVALID', JSON.stringify(errors));
    if (job.artifact_profile !== plan.profiles.artifact) fail('PROFILE_MISMATCH', 'job and execution artifact differ');
    if (job.approved_asset?.state === 'human_approved_locked') fail('APPROVED_MASTER_ROUTE', 'use the existing approved-media materializer, not a new generation packet');
    const compiled = pending.length ? core.compileVisualPrompt(job) : {};
    legacy = { ref: f.ref, sha256: f.sha256, visual_brief: job.visual_brief ?? null, render_spec: job.render_spec ?? null, ...compiled };
  }
  const origins = {};
  for (const key of ['canvas', 'text_policy', 'density', 'watermark', 'watermark_layer']) origins[key] = task[key] !== undefined ? 'task' : preset[key] !== undefined ? 'preset' : 'profile_or_renderer_default';
  for (const key of Object.keys(theme)) origins[`theme.${key}`] = task.theme?.[key] !== undefined ? 'task' : preset.theme?.[key] !== undefined ? 'preset' : profiles.brand?.execution_defaults?.theme?.[key] !== undefined ? 'brand' : 'renderer_default_not_canonical_brand_token';
  const packet = {
    schema_version: EXECUTION_VERSION, kind: 'visual_execution', status: pending.length ? 'RENDER_REQUIRED' : 'COMPOSITION_REQUIRED',
    request: plan.request, request_hash: digest(plan), source: { ref: source.ref, sha256: source.sha256, scope: plan.source.scope },
    profiles: Object.fromEntries(Object.entries(profiles).map(([axis, p]) => [axis, { id: plan.profiles[axis], version: p.profile_version ?? p.schema_version, sha256: digest(p) }])),
    canvas, theme, density, text_policy: policy, watermark, watermark_layer: watermarkLayer, field_origins: origins,
    resolved_requirements: {
      artifact: { primary_job: profiles.artifact.primary_job, composition: profiles.artifact.composition, acceptance: profiles.artifact.acceptance, readability: profiles.artifact.readability_gate },
      surface: profiles.surface.visual_defaults ?? profiles.surface.constraints,
      brand: profiles.brand ? { stable_visual_properties: profiles.brand.stable_visual_properties, palette: profiles.brand.palette, materiality: profiles.brand.line_and_materiality } : null,
      density_review: 'Declared intent, not measured coverage. Review actual semantic/visual density; explicit slots own geometry.',
    },
    layers, caption: plan.caption ?? '', legacy,
    generation: pending.map((l) => ({ layer_id: l.id, instruction: l.instruction, pixel_slot: l.pixel_slot,
      constraints: 'Generate this illustrative layer only. Do not draw data geometry, numbers, citations, watermark or source photo identity. Use the supplied source and authorized reference traits only.',
      external_generator_required: true })),
    qa: { source_semantics: 'NOT_REVIEWED', visual: 'NOT_REVIEWED', publication: 'NOT_AUTHORIZED' },
  };
  packet.execution_hash = digest(packet);
  return packet;
}

/** A fresh output directory prevents stale PNGs being mistaken for a failed rerun. */
export function prepareOutput(outDir) {
  if (!outDir) fail('OUTPUT_REQUIRED', 'provide a separate output directory');
  if (existsSync(outDir) && readdirSync(outDir).length) fail('OUTPUT_EXISTS', 'use a new empty output directory; previous runs and input files are never overwritten');
}


function imageElement(file, l) {
  const b = l.pixel_slot;
  const ratio = l.fit === 'cover' ? 'xMidYMid slice' : 'xMidYMid meet';
  return `<svg x="${b.x}" y="${b.y}" width="${b.width}" height="${b.height}" viewBox="0 0 ${b.width} ${b.height}" overflow="hidden"><image width="${b.width}" height="${b.height}" preserveAspectRatio="${ratio}" xlink:href="data:image/png;base64,${file.bytes.toString('base64')}"/></svg>`;
}

/**
 * Repair budget lineage (SUE-1426 fix S4). The budget is a WORKFLOW CONTROL, not tamper-proof: omitting --repair-of /
 * --previous starts a new base, and anyone who can copy a directory can start over. What it does stop is the honest
 * mistakes: counting a failed run as a round, a second "local fix" from the same base (including fan-out into a
 * different output directory) and repairing a different request with the same flag.
 *
 * lineage_root = hash of the base request identity (request text + source ref [+ series id]); a repair must carry the
 * same root. The ledger is an append-only JSONL file BESIDE the base directory (`<base>.repair-ledger.jsonl`), so the
 * base directory itself stays byte-identical.
 */
export const lineageRootOf = (parts) => digest(parts);
export const ledgerPathFor = (baseDir) => `${resolve(baseDir)}.repair-ledger.jsonl`;
export function readLedger(baseDir) {
  const path = ledgerPathFor(baseDir);
  if (!existsSync(path)) return [];
  return readFileSync(path, 'utf8').split('\n').filter(Boolean).map((line, i) => {
    try { return JSON.parse(line); } catch { return fail('LEDGER_CORRUPT', `${path} line ${i + 1} is not JSON; the repair ledger is append-only and fails closed`); }
  });
}
export const countedRepairs = (baseDir, root) => readLedger(baseDir).filter((e) => e.lineage_root === root && e.outcome === 'repair_ok').length;
export function appendLedger(baseDir, entry) { appendFileSync(ledgerPathFor(baseDir), `${JSON.stringify(entry)}\n`); }
/** Shared pre-run check for both executors. Returns { priorOk, priorRound }. Throws LINEAGE_MISMATCH / REPAIR_LIMIT. */
export function checkRepairLineage(prior, priorStatus, baseDir, root, { enforceLimit = true } = {}) {
  if (!prior.lineage_root) fail('LINEAGE_MISMATCH', 'the previous run carries no lineage_root (made before the repair ledger); start a new base version');
  if (prior.lineage_root !== root) fail('LINEAGE_MISMATCH', 'the previous run was made from a different request/source/series; a repair must keep the same base. Omit the flag to start a new base.');
  // Fail closed: a receipt that has a lineage but no integer repair_round must not be read as round 0 (that would reset the budget).
  if (!Number.isInteger(prior.repair_round) || prior.repair_round < 0) fail('LINEAGE_MISMATCH', 'the previous receipt has lineage_root but no non-negative integer repair_round; the repair budget cannot be established, start a new base version');
  const priorOk = isRenderedOk(priorStatus), priorRound = prior.repair_round;
  if (priorOk && enforceLimit) enforceRepairLimit(priorRound, baseDir, root);
  return { priorOk, priorRound };
}
export function enforceRepairLimit(priorRound, baseDir, root) {
  if (priorRound >= 1) fail('REPAIR_LIMIT', 'already repaired once; start a new base version instead of a second local fix');
  if (countedRepairs(baseDir, root) >= 1) fail('REPAIR_LIMIT', `a repair of this base is already recorded in ${ledgerPathFor(baseDir)}; a second local fix (including from another output directory) needs a new base version`);
}

/** Writes clean master + optional derivative + packet/receipt; never publishes. */
export async function executeVisual(plan, { baseDir = process.cwd(), preset = {}, outDir, rasterizer = 'auto', repairOf = null } = {}) {
  // Enforced repair budget: one base version + ONE local fix. `repairOf` is the prior run directory. A round is only
  // COUNTED when the prior run was rendered-OK and this run completes OK (see lineage helpers above).
  const lineage = lineageRootOf({ kind: 'visual', request: plan?.request ?? null, source_ref: plan?.source?.ref ?? null });
  let repairRound = 0, repairPrior = null, priorOk = false;
  if (repairOf) {
    const prior = JSON.parse(readFileSync(resolve(repairOf, 'receipt.json'), 'utf8'));
    const chk = checkRepairLineage(prior, prior.status, repairOf, lineage);
    priorOk = chk.priorOk; repairRound = chk.priorRound;
    repairPrior = { image_sha256: prior.outputs?.image?.sha256 ?? null, request_hash: prior.request_hash };
  }
  prepareOutput(outDir);
  const packet = await compileExecution(plan, { baseDir, preset });
  let adapter = findRasterizer(rasterizer);
  packet.rasterizer = adapter ? { name: adapter.name, version: adapter.version } : null;
  if (!adapter || packet.status === 'RENDER_REQUIRED') {
    if (!adapter) packet.missing_capabilities = ['local_svg_rasterizer'];
    mkdirSync(outDir, { recursive: true });
    writeFileSync(resolve(outDir, 'execution.json'), `${JSON.stringify(packet, null, 2)}\n`);
    return packet;
  }
  if (requestsBundledFont(packet.theme.font_family) || packet.layers.some((l) => requestsBundledFont(l.font_family))) {
    adapter = { ...adapter, env: bundledFontEnv() }; // rasterizer sees only the bundled fonts: same result on any machine
    for (const w of new Set(packet.layers.filter((l) => l.kind === 'text').flatMap((l) => [l.weight, ...(l.emphasis ?? []).map((e) => e.weight ?? l.weight)]))) verifyBundledResolution(w, adapter.env);
  }
  const { width, height } = packet.canvas;
  const measure = textMeasurer(adapter, packet.theme.font_family);
  const source = localInput(packet.source.ref, baseDir, packet.source.sha256);
  const inputs = [source]; if (plan.job_ref) inputs.push(localInput(plan.job_ref, baseDir));
  let article = null;
  if (plan.job_ref) { try { article = JSON.parse(source.bytes); } catch { /* article check requires the actual article JSON */ } }
  const elements = [], charts = [], textEvidence = [], imageEvidence = [], generated = [];
  const exclusions = [], contrastChecks = [], scrimEvidence = [], isText = new Set();
  for (const l of packet.layers) {
    const b = l.pixel_slot;
    if (l.kind === 'text') {
      const rich = l.balance || l.emphasis || l.letter_spacing !== undefined || l.font_family || l.normalize || l.optical_margin || l.min_contrast !== undefined;
      if (!rich) {
        const lines = wrapText(l.text, { width: b.width, height: b.height, size: l.font_size, weight: l.weight, maxLines: l.max_lines, lineHeight: l.line_height }, measure);
        const x = b.x + (l.align === 'middle' ? b.width / 2 : l.align === 'end' ? b.width : 0);
        elements.push(`<text font-family="${esc(packet.theme.font_family)}" font-size="${l.font_size}" font-weight="${l.weight}" fill="${l.color ?? packet.theme.foreground}" text-anchor="${l.align}">${lines.map((t, i) => `<tspan x="${x}" y="${b.y + l.font_size + i * l.font_size * l.line_height}">${esc(t)}</tspan>`).join('')}</text>`);
        isText.add(elements.length - 1);
        textEvidence.push({ id: l.id, text: l.text, source_ref: l.source_ref, lines, font_size: l.font_size, slot: b });
        continue;
      }
      const family = l.font_family ?? packet.theme.font_family;
      const printed = l.normalize ? normalizeKoreanText(l.text) : l.text;
      const emph = locateEmphasis(printed, (l.emphasis ?? []).map((e) => ({ ...e, weight: e.weight ?? l.weight })));
      if (requestsBundledFont(family)) { assertFontCoverage(printed, l.weight); for (const e of emph) assertFontCoverage(printed.slice(e.start, e.end), e.weight); }
      const lm = family === packet.theme.font_family ? measure : textMeasurer(adapter, family);
      const spaced = (t, z, w) => lm(t, z, w) + (l.letter_spacing ?? 0) * z * [...t].length;
      const lines = l.balance
        ? balancedWrap(printed, { width: b.width, size: l.font_size, weight: l.weight, maxLines: l.max_lines, emphasis: emph }, spaced)
        : wrapText(printed, { width: b.width, height: b.height, size: l.font_size, weight: l.weight, maxLines: l.max_lines, lineHeight: l.line_height }, spaced);
      if (lines.length * l.font_size * l.line_height > b.height) fail('TEXT_OVERFLOW', `${l.id}: ${lines.length} lines exceed the slot height; text was not truncated`);
      const x = b.x + (l.align === 'middle' ? b.width / 2 : l.align === 'end' ? b.width : 0) - (l.optical_margin && l.align === 'start' ? Math.round(l.font_size * 0.04) : 0);
      let cursor = 0; const tsp = [];
      lines.forEach((t, i) => {
        const at = printed.indexOf(t, cursor); cursor = at + t.length;
        const runs = weightRuns(printed, at, at + t.length, l.weight, emph).map((r) => `<tspan${r.weight !== l.weight ? ` font-weight="${r.weight}"` : ''}${r.color ? ` fill="${r.color}"` : ''}>${esc(r.text)}</tspan>`).join('');
        tsp.push(`<tspan x="${x}" y="${b.y + l.font_size + i * l.font_size * l.line_height}">${runs}</tspan>`);
      });
      elements.push(`<text font-family="${esc(family)}" font-size="${l.font_size}" font-weight="${l.weight}"${l.letter_spacing ? ` letter-spacing="${(l.letter_spacing * l.font_size).toFixed(2)}"` : ''} fill="${l.color ?? packet.theme.foreground}" text-anchor="${l.align}" xml:space="preserve">${tsp.join('')}</text>`);
      isText.add(elements.length - 1);
      textEvidence.push({ id: l.id, text: l.text, ...(printed !== l.text ? { printed_text: printed } : {}), source_ref: l.source_ref, lines, font_size: l.font_size, slot: b, orphan: hasOrphan(lines) });
      if (l.min_contrast !== undefined) contrastChecks.push({ layer: l, rect: { x: b.x, y: b.y, width: b.width, height: Math.ceil(lines.length * l.font_size * l.line_height) } });
    } else if (l.kind === 'solid') {
      let opacityStops = l.gradient;
      if (l.auto_scrim) {
        const a = l.auto_scrim, targets = packet.layers.filter((t) => t.kind === 'text' && a.for.includes(t.id));
        if (targets.length !== a.for.length) fail('INVALID_AUTO_SCRIM', `${l.id}: auto_scrim.for must name text layers of this plan`);
        const under = decodePng(rasterize(svgDocument(width, height, `<rect width="${width}" height="${height}" fill="${packet.theme.background}"/>${elements.filter((_, i) => !isText.has(i)).join('')}`), adapter));
        let alpha = 0;
        for (const t of targets) {
          if (t.pixel_slot.y < b.y + (a.feather ?? 0) * b.height) fail('INVALID_AUTO_SCRIM', `${l.id}: ${t.id} starts inside the feathered edge; move the scrim up or reduce feather`);
          const tc = hexToRgb(t.color ?? packet.theme.foreground), bg = worstBackground(under, t.pixel_slot, tc);
          const o = autoScrimOpacity(bg, tc, hexToRgb(l.color), a.target_contrast, a.max_opacity ?? 0.92);
          if (o === null) fail('CONTRAST_FAIL', `${l.id}: ${t.id} cannot reach contrast ${a.target_contrast} even at max scrim opacity`);
          alpha = Math.max(alpha, o);
        }
        const f = a.feather ?? 0; opacityStops = f > 0 ? [[0, 0], [f, alpha], [1, alpha]] : [[0, alpha], [1, alpha]];
        scrimEvidence.push({ id: l.id, opacity: alpha, target_contrast: a.target_contrast, for: a.for });
      }
      if (opacityStops) {
        const gid = `scrim-${l.id}`;
        elements.push(`<defs><linearGradient id="${gid}" x1="0" y1="0" x2="0" y2="1">${opacityStops.map(([o, a]) => `<stop offset="${o}" stop-color="${l.color}" stop-opacity="${a}"/>`).join('')}</linearGradient></defs><rect x="${b.x}" y="${b.y}" width="${b.width}" height="${b.height}" fill="url(#${gid})"/>`);
      } else elements.push(`<rect x="${b.x}" y="${b.y}" width="${b.width}" height="${b.height}" fill="${l.color}"/>`);
    } else {
      const file = localInput(l.ref, baseDir, l.sha256); inputs.push(file);
      if (l.kind === 'chart') {
        const spec = JSON.parse(file.bytes);
        if (article?.verification) {
          const errors = validateChartAgainstArticle(spec, article);
          if (errors.length) fail('CHART_CLAIM', errors.join('; '));
        }
        const result = renderChartPanel(spec, { width: b.width, height: b.height, theme: packet.theme, measure });
        elements.push(`<svg x="${b.x}" y="${b.y}" width="${b.width}" height="${b.height}" overflow="hidden">${result.svg}</svg>`);
        charts.push({ id: l.id, source_ref: l.ref, source_sha256: file.sha256, ...result, svg: undefined });
      } else {
        const el = imageElement(file, l);
        elements.push(el);
        if (isGeneratedLayer(l)) generated.push({ layer: l, el });
        const requiredScale = l.fit === 'cover'
          ? Math.max(b.width / l.native_geometry.width, b.height / l.native_geometry.height)
          : Math.min(b.width / l.native_geometry.width, b.height / l.native_geometry.height);
        imageEvidence.push({
          id: l.id, ref: l.ref, source_sha256: file.sha256, mode: l.mode, fit: l.fit,
          source_geometry: l.native_geometry, slot: b,
          resolution: {
            required_scale: Number(requiredScale.toFixed(4)),
            upsampled: requiredScale > 1,
            status: requiredScale > 1 ? 'UPSCALE_WARNING' : 'NATIVE_OR_DOWNSCALE',
          },
          rights_note: l.rights_note, protect: l.protect ?? [],
        });
      }
    }
    // Background watermarks may sit below evidence marks, but not below copy.
    if (packet.watermark_layer === 'overlay' || l.kind === 'text') exclusions.push({ zone_id: l.id, ...l.slot });
  }
  if (packet.layers.some((layer) => layer.mockup_risk === true)) {
    elements.push(`<text x="${Math.round(width * 0.05)}" y="${Math.round(height * 0.985)}" font-family="${esc(packet.theme.font_family)}" font-size="${Math.max(14, Math.round(width * 0.018))}" fill="${packet.theme.foreground}">ILLUSTRATIVE / 가상 예시</text>`);
  }
  const contrastEvidence = [];
  if (contrastChecks.length) {
    const base = decodePng(rasterize(svgDocument(width, height, `<rect width="${width}" height="${height}" fill="${packet.theme.background}"/>${elements.filter((_, i) => !isText.has(i)).join('')}`), adapter));
    for (const c of contrastChecks) {
      const tc = hexToRgb(c.layer.color ?? packet.theme.foreground), bg = worstBackground(base, c.rect, tc), ratio = contrastRatio(tc, bg);
      contrastEvidence.push({ id: c.layer.id, ratio: Number(ratio.toFixed(2)), min: c.layer.min_contrast, result: ratio >= c.layer.min_contrast ? 'PASS' : 'FAIL' });
    }
    const bad = contrastEvidence.filter((e) => e.result === 'FAIL');
    if (bad.length) fail('CONTRAST_FAIL', bad.map((e) => `${e.id} ${e.ratio} < ${e.min}`).join('; '));
  }
  const background = `<rect width="${width}" height="${height}" fill="${packet.theme.background}"/>`;
  const cleanSvg = svgDocument(width, height, background + elements.join(''));
  const master = rasterize(cleanSvg, adapter);
  const m = decodePng(master);
  if (m.width !== width || m.height !== height) fail('OUTPUT_GEOMETRY', 'rasterizer returned a different size');
  // Generated-image honesty: evidence + placeholder check + proof the asset is visible in the composed master.
  const generationEvidence = [];
  for (const g of generated) {
    const b = g.layer.pixel_slot, reasons = [...g.layer.generation_check.reasons];
    const without = rasterize(svgDocument(width, height, background + elements.filter((e) => e !== g.el).join('')), adapter);
    const a = decodePng(master), z = decodePng(without), ch = a.channels ?? 4;
    let changed = 0, total = 0;
    for (let y = Math.max(0, b.y); y < Math.min(height, b.y + b.height); y++) for (let x = Math.max(0, b.x); x < Math.min(width, b.x + b.width); x++) {
      const o = (y * width + x) * ch; total++;
      if (Math.abs(a.pixels[o] - z.pixels[o]) > 8 || Math.abs(a.pixels[o + 1] - z.pixels[o + 1]) > 8 || Math.abs(a.pixels[o + 2] - z.pixels[o + 2]) > 8) changed++;
    }
    const ratio = total ? changed / total : 0, consumed = ratio >= 0.02;
    generationEvidence.push({ id: g.layer.id, ...(g.layer.generation ?? {}), distinct_colours: g.layer.generation_check.distinct_colours, evidence_level: 'SELF_ATTESTED', machine_verified: ['asset_in_final_png'], response_sha256: g.layer.generation_check.response_sha256, flat_art_attestation: g.layer.generation_check.flat_art_attestation, slot_pixels: total, slot_pixels_changed_by_asset: changed, consumed_ratio: Number(ratio.toFixed(4)), asset_in_final_png: consumed, not_verified_reasons: reasons });
  }
  const config = resolveWatermark(packet.watermark, { exclusion_zones: exclusions });
  const wmAdapter = { render: (svg) => rasterize(svg, adapter), version: adapter.version };
  let final = master, watermarkEvidence = null;
  if (config.enabled && packet.watermark_layer === 'background') {
    const base = rasterize(svgDocument(width, height, background), adapter);
    const marked = applyWatermark(base, config, { masterRef: 'background-layer', rasterizer: wmAdapter });
    final = rasterize(svgDocument(width, height, `<image width="${width}" height="${height}" xlink:href="data:image/png;base64,${marked.bytes.toString('base64')}"/>${elements.join('')}`), adapter);
    const composed = decodePng(final);
    final = encodePng({ ...composed, text: { ...composed.text, [WATERMARK_CHUNK_KEY]: JSON.stringify({ master_sha256: sha256(master), text: config.text, layer: 'background' }) } });
    watermarkEvidence = { ...marked.lineage, composed_layer: 'background', final_sha256: sha256(final), final_master_sha256: sha256(master) };
  } else {
    const marked = applyWatermark(master, config, { masterRef: 'master.png', rasterizer: wmAdapter });
    final = marked.bytes; watermarkEvidence = marked.lineage ?? null;
  }
  // Resolve actual file identities before writing. Never overwrite an input,
  // including via a symlinked output directory.
  mkdirSync(outDir, { recursive: true });
  const realOut = realpathSync(outDir);
  for (const name of ['master.png', 'image.png', 'master.svg', 'execution.json', 'receipt.json']) {
    const target = resolve(realOut, name);
    for (const f of inputs) if (realpathSync(f.path) === target || (existsSync(target) && realpathSync(target) === realpathSync(f.path))) fail('SOURCE_OVERWRITE', `output would replace input ${f.ref}`);
  }
  for (const f of inputs) localInput(f.ref, baseDir, f.sha256);
  packet.status = !generationEvidence.length ? RENDER_OK
    : generationEvidence.some((g) => g.not_verified_reasons.length) ? GENERATION_NOT_VERIFIED
    : generationEvidence.some((g) => !g.asset_in_final_png) ? GENERATED_NOT_USED : GENERATED_OK;
  const repairCounted = Boolean(repairOf) && priorOk && isRenderedOk(packet.status);
  const receipt = {
    schema_version: EXECUTION_VERSION, lineage_root: lineage, repair_round: repairCounted ? repairRound + 1 : repairRound, repair_counted: repairCounted, repair_of: repairPrior, status: packet.status, request_hash: packet.request_hash, execution_hash: packet.execution_hash,
    renderer: { tool: 'aes-visual-execution', version: EXECUTION_VERSION, ...packet.rasterizer, font_stack: packet.theme.font_family },
    inputs: inputs.map((f) => ({ ref: f.ref, sha256: f.sha256 })), geometry: packet.canvas,
    outputs: (() => { const d = isRenderedOk(packet.status) ? '' : 'rejected/'; return { master: { ref: `${d}master.png`, sha256: sha256(master) }, image: { ref: `${d}image.png`, sha256: sha256(final) }, svg: { ref: `${d}master.svg`, sha256: sha256(cleanSvg) } }; })(),
    text: textEvidence, charts, images: imageEvidence, generation: generationEvidence, watermark: watermarkEvidence,
    mockup_labels: packet.layers.filter((layer) => layer.mockup_risk === true).map((layer) => ({ layer_id: layer.id, text: 'ILLUSTRATIVE / 가상 예시', reason: 'mockup_risk' })),
    checks: { output_geometry: 'PASS', text_fit: 'PASS', inputs_rechecked: 'PASS', numeric_render_binding: charts.length ? 'PASS' : 'NOT_APPLICABLE', generated_image: generationEvidence.length ? packet.status : 'NOT_APPLICABLE', contrast: contrastEvidence.length ? 'PASS' : 'NOT_APPLICABLE', ...(scrimEvidence.length ? { auto_scrim: scrimEvidence } : {}), ...(contrastEvidence.length ? { contrast_detail: contrastEvidence } : {}), actual_pixel_semantic_review: 'NOT_RUN_PHASE4', source_truth: 'NOT_ESTABLISHED_BY_RENDERER' },
    api_calls: 0, publication_authorized: false,
  };
  // A failed/unverified result must not leave a success-looking PNG: pixels go under rejected/, never at the top level.
  const accepted = isRenderedOk(packet.status), pixelDir = accepted ? outDir : resolve(outDir, 'rejected');
  if (!accepted) mkdirSync(pixelDir, { recursive: true });
  writeFileSync(resolve(pixelDir, 'master.svg'), cleanSvg);
  writeFileSync(resolve(pixelDir, 'master.png'), master);
  writeFileSync(resolve(pixelDir, 'image.png'), final);
  writeFileSync(resolve(outDir, 'execution.json'), `${JSON.stringify(packet, null, 2)}\n`);
  writeFileSync(resolve(outDir, 'receipt.json'), `${JSON.stringify(receipt, null, 2)}\n`);
  if (repairOf) appendLedger(repairOf, { lineage_root: lineage, outcome: repairCounted ? 'repair_ok' : 'repair_not_counted', status: packet.status, prior_ok: priorOk, receipt_sha256: sha256(readFileSync(resolve(outDir, 'receipt.json'))) });
  return { ...packet, receipt };
}
